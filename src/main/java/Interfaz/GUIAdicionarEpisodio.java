    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
            String idSerie = txtIdSerie.getText().trim();
            String titulo = txtTitulo.getText().trim();
            int noEpisodio = Integer.parseInt(txtNoEpisodio.getText().trim());

            if (idSerie.isEmpty() || titulo.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.",
                        "Datos incompletos", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            servicios.ServicioContenido.getInstance().addEpisodioASerie(idSerie, noEpisodio, titulo);
            javax.swing.JOptionPane.showMessageDialog(this, "Episodio agregado correctamente a la serie " + idSerie + ".");

            txtIdSerie.setText("");
            txtNoEpisodio.setText("");
            txtTitulo.setText("");
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "El número de episodio debe ser un valor numérico.",
                    "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

